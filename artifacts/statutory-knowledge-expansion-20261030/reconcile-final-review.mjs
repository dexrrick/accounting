// Persist the independent reviewer's final reconciliation delivered to the supervisor.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const dir = new URL('./', import.meta.url);
const read = file => JSON.parse(readFileSync(new URL(file, dir), 'utf8').replace(/^\uFEFF/, ''));
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const r = read('independent-final-review.json');
const final = read('final75.json');
const baseline = read('baseline75.json');
r.reviewedAtUTC = new Date().toISOString();
r.status = 'BOUNDED_REVIEW_COMPLETE_NO_NEW_MATERIAL_CODE_FINDINGS';
r.reconciliation = 'Supervisor persisted final read-only reviewer messages; answer grades were independently adjudicated by answer_review.';
r.counts = { CORRECT: 20, PARTIAL: 7, INCORRECT: 1, UNSUPPORTED: 47 };
r.perAuthority.MAS = { CORRECT: 5, PARTIAL: 0, INCORRECT: 0, UNSUPPORTED: 10 };
r.newlyCorrect = [...new Set([...r.newlyCorrect, 'mas-03'])];
const mas03 = r.grades.find(row => row.id === 'mas-03');
Object.assign(mas03, { grade: 'CORRECT', failureCategory: 'NONE', reason: 'Complete Form25A financial-year-end rule, FAQ13 CY2026 waiver/2027 discontinuation and separate fund-level scope answer; FYE needed for a specific date.', reviewMethod: 'INDEPENDENT_FINAL_DELTA_REVIEW' });
for (const row of r.grades) row.answerSha256 = hash(final.outcomes.find(item => item.id === row.id).answer);
const identical = final.outcomes.filter(row => row.answer === baseline.outcomes.find(old => old.id === row.id).answer).length;
r.answerIdentity = { identical, changedRead: 75 - identical };
for (const file of Object.keys(r.artifactSha256)) r.artifactSha256[file] = hash(readFileSync(new URL(file, dir)));
for (const file of Object.keys(r.reviewedSourceSha256)) r.reviewedSourceSha256[file] = hash(readFileSync(new URL('../../' + file, dir)));
Object.assign(r.codeFindings.find(item => item.id === 'CPF_DATE_OWNER'), { status: 'FIXED_INDEPENDENTLY_RECHECKED', evidence: 'Expense-reimbursement, training-expense and competing-date probes withheld computed dates; explicit conditional-bonus repayment date correctly yields 15/09/2027.' });
r.finalCodeReview = 'Independent bounded probes confirmed scoped compound-family fallback veto, advisory-versus-payroll classification, preserved hypothetical prorated-payroll route, and mixed CPF calculation/refund without fabricated journal or amount.';
r.limitations = r.limitations.filter(value => !/Stored final75|still under correction/.test(value));
const old = r.previous60ChangedReview;
Object.assign(old, { changedReviewed: 9, priorCorrectInChanged: 7, priorCorrectPreservedInChanged: 7 });
old.grades = old.grades.filter(row => row.id !== 'fresh-cpf-02');
for (const row of old.grades) row.answerSha256 = hash(read(row.cohort + '.json').outcomes.find(item => item.id === row.id).answer);
delete old.unchanged50;
old.unchanged51 = 'Fifty-one byte-identical answers inherit prior grades and were not re-adjudicated in this bounded review; no new blanket correctness claim is made for those inherited grades.';
writeFileSync(new URL('independent-final-review.json', dir), JSON.stringify(r, null, 2) + '\n');
console.log(JSON.stringify({ counts: r.counts, newlyCorrect: r.newlyCorrect.length, identity: r.answerIdentity }));
